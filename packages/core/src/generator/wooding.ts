/** Spec of a Wooding level (76–100). */
export function woodingSpec(index: number): LevelSpec {
  const spec = WOODING_SPECS.find((s) => s.index === index);
  if (!spec) throw new Error(`no Wooding spec for level ${index}`);
  return spec;
}
