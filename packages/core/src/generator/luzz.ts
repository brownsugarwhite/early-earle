/** Spec of a Luzz level (51–75). */
export function luzzSpec(index: number): LevelSpec {
  const spec = LUZZ_SPECS.find((s) => s.index === index);
  if (!spec) throw new Error(`no Luzz spec for level ${index}`);
  return spec;
}
